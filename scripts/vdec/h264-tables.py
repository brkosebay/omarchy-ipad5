"""Offline, pinned-source H.264 VLC generator and exact comparator.

No kext, device, network, compiler, or third-party Python package is needed.
The upstream file is preserved verbatim in upstream/h264_vlc.h.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import zlib

COMMIT = "9453ad8ebdd42a5e5a384c21cd5f6bc2c86aa6d8"
URL = f"https://github.com/TexasInstruments/img-vxe-vxd/blob/{COMMIT}/decoder/h264_vlc.h"
SHA256 = "9b349a315038817651a8f6c0be87bb82321f9b046901957a3d65e73f6f1eeb66"
PSB_SHA256 = "096be85abdd08365e6a701a67fcbdf224bd181f3377e1d1e1bb84a274baf3285"
SOURCE = Path(__file__).with_name("upstream") / "h264_vlc.h"


def array(text, name):
    """Parse numeric C initializers only; reject unrecognized expressions."""
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    match = re.search(r"\b" + re.escape(name) + r"\s*(?:\[[^\]]*\])+\s*=\s*\{(.*?)\};", text, re.S)
    if not match:
        raise ValueError(f"missing initializer: {name}")
    body = match[1]
    tokens = re.findall(r"0[xX][0-9a-fA-F]+|\d+", body)
    if re.sub(r"0[xX][0-9a-fA-F]+|\d+|[\s,{}]", "", body):
        raise ValueError(f"unsupported initializer: {name}")
    return [int(t, 16 if t.lower().startswith("0x") else 10) for t in tokens]


def packed(source=SOURCE):
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError("GPL source SHA-256 differs from pinned upstream")
    nums = array(raw.decode(), "h264_vlc_table_data")
    if len(nums) != 544 * 3:
        raise ValueError(f"expected 1632 values, found {len(nums)}")
    result = []
    for opcode, width, symbol in zip(nums[::3], nums[1::3], nums[2::3]):
        if not (0 <= opcode < 8 and 0 <= width < 8 and 0 <= symbol < 512):
            raise ValueError("VLC field overflow")
        result.append((opcode << 12) | (width << 9) | symbol)
    return result


def render_header(values, workspace=False):
    prefix = "VXD" if workspace else "APPLE_VXD"
    symbol = "vxd" if workspace else "apple_vxd"
    guard = f"__{prefix}_H264_TABLES_H__"
    crc = zlib.crc32(struct.pack("<544H", *values))
    byte_define = f"#define {prefix}_H264_VLC_BYTES\t1088\n" if workspace else ""
    rows = "\n".join("\t" + ", ".join(f"0x{v:04x}" for v in values[i:i + 8]) + ","
                     for i in range(0, len(values), 8))
    return f"""/* SPDX-License-Identifier: GPL-2.0 */
/*
 * Copyright (c) Imagination Technologies Ltd.
 * Copyright (c) 2021 Texas Instruments Incorporated - http://www.ti.com/
 *
 * H.264 CAVLC decode table, generated by h264-tables.py from
 * img-vxe-vxd decoder/h264_vlc.h (h264_vlc_table_data).
 * Upstream author: Angela Stegmaier <angelabaker@ti.com>
 * {URL}
 * Source SHA-256: {SHA256}
 * Packing: opcode << 12 | width << 9 | symbol. No Apple binary input.
 * CRC-32 of the 1088 little-endian bytes: 0x{crc:08x}.
 */
#ifndef {guard}
#define {guard}

#include <linux/types.h>

#define {prefix}_H264_VLC_ENTRIES\t544
{byte_define}#define {prefix}_H264_VLC_CRC32\t0x{crc:08x}

/* opcode[14:12] | width[11:9] | symbol[8:0] */
static const u16 {symbol}_h264_vlc_table[{prefix}_H264_VLC_ENTRIES] = {{
{rows}
}};

#endif /* {guard} */
"""


def compare(expected, actual, label):
    if expected != actual:
        mismatch = next((i for i, (a, b) in enumerate(zip(expected, actual)) if a != b), None)
        raise ValueError(f"{label}: mismatch at {mismatch}; lengths {len(expected)}/{len(actual)}")
    return {"comparison": label, "matching_entries": len(expected)}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", type=Path, default=SOURCE)
    ap.add_argument("--compare", action="append", type=Path, default=[], help="kernel or workspace header")
    ap.add_argument("--psb", type=Path, help="pinned psb_video src/pnw_H264.c")
    ap.add_argument("--write", type=Path, help="generate header; otherwise print JSON evidence")
    ap.add_argument("--workspace", action="store_true", help="use workspace symbol names")
    args = ap.parse_args()
    values = packed(args.source)
    checks = []
    for path in args.compare:
        text = path.read_text()
        name = "apple_vxd_h264_vlc_table" if "apple_vxd_h264_vlc_table[" in text else "vxd_h264_vlc_table"
        checks.append(compare(values, array(text, name), str(path)))
    if args.psb:
        raw = args.psb.read_bytes()
        if hashlib.sha256(raw).hexdigest() != PSB_SHA256:
            raise ValueError("psb source SHA-256 differs from pinned upstream")
        psb = array(raw.decode(), "ui16H264VLCTableData")
        if len(psb) != 520:
            raise ValueError(f"expected 520 psb entries, found {len(psb)}")
        checks.append(compare(values[:520], psb, "MIT psb_video prefix"))
    data = struct.pack("<544H", *values)
    if args.write:
        args.write.write_text(render_header(values, args.workspace))
    print(json.dumps({"source_url": URL, "source_commit": COMMIT,
                      "source_sha256": SHA256, "entries": len(values),
                      "table_sha256": hashlib.sha256(data).hexdigest(),
                      "table_crc32": f"0x{zlib.crc32(data):08x}", "checks": checks}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as error:
        sys.exit(str(error))
